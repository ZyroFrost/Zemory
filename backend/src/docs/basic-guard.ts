// plan/28 §0m — the gate of a Basic set: a machine with no zemory and possibly no Node and no Git. Two layers the host runs
// on a bare Windows machine (measured 14/10 with the native host binary):
//   ① native permissions (`permissions.ask` / `deny` in .claude/settings.json), taken from each rule's gate.json › native;
//   ② one PreToolUse hook in Windows PowerShell 5.1 that answers with the JSON decision — exit code 2 alone does not block
//      on a machine without Git, a Node hook does not run at all where Node is missing (and the host says nothing).
// A rule's own hook.cjs is Memory-only: a Basic set leaves it out (BASIC_DROP) and its text is read first instead.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { SECRET_VALUES } from "./rule-hooks-src.js";
import { SHELF } from "./harness-names.js";
import type { Part } from "./store.js";

export const BASIC_GUARD_REL = ".claude/hooks/guard.ps1";
export const BASIC_SETTINGS_REL = ".claude/settings.json";
/** The files of a rule part a Basic set does not carry: the Node hooks (hook.cjs · hook_test.cjs · hook_names.cjs). */
export const BASIC_DROP = /(^|\/)hook([-_][a-z]+)?\.cjs$/;
export const BASIC_MATCHER = "Write|Edit|MultiEdit|NotebookEdit";
/**
 * The hook command: anchored at the project root through CLAUDE_PROJECT_DIR, written without `$` so Git Bash, cmd and
 * PowerShell all pass it to powershell.exe unchanged. No variable (another host) ⇒ the path is relative to the working folder.
 */
export const BASIC_GUARD_COMMAND =
  `powershell -NoProfile -ExecutionPolicy Bypass -Command "& ([IO.Path]::Combine([string][Environment]::GetEnvironmentVariable('CLAUDE_PROJECT_DIR'), '${BASIC_GUARD_REL}'))"`;
/** Where the marker records the permission lines the assembly added, so a line the repo removed is not added back. */
const MARKER_KEY = "basic_native";

/** The guard script. ASCII only (PowerShell 5.1 reads a BOM-less file in the ANSI code page). */
export function basicGuardSource(): string {
  const secrets = JSON.stringify(SECRET_VALUES);
  return [
    "# Generated by zemory for a Basic set (plan/28 0m) - change the source in zemory (basic-guard.ts), not this copy.",
    "# PreToolUse guard in Windows PowerShell 5.1: runs where the machine has no Node and no Git. It answers with the JSON",
    "# decision on stdout; 'deny' also exits 2 (the fallback channel).",
    "#   Rule_Gate_44_RepoScope      a file written outside the open project            => ask (the person decides in the app)",
    "#   Rule_Gate_21_WhatEntersGit  a secret value written into a code file git tracks => deny (in a test file: ask)",
    "# Anything it cannot read lets the call through: the text of the rules still holds (Rule_Keys_61_HookSafetyNet).",
    "$ErrorActionPreference = 'Stop'",
    "try { [Console]::InputEncoding = [Text.Encoding]::UTF8; [Console]::OutputEncoding = [Text.Encoding]::UTF8 } catch {}",
    "try { $p = [Console]::In.ReadToEnd() | ConvertFrom-Json } catch { exit 0 }",
    "",
    "function Say([string]$decision, [string]$reason) {",
    "  $o = @{ hookSpecificOutput = @{ hookEventName = 'PreToolUse'; permissionDecision = $decision; permissionDecisionReason = $reason } }",
    "  [Console]::Out.Write(($o | ConvertTo-Json -Compress -Depth 4))",
    "  [Console]::Out.Flush()",
    "  # 'exit 2' inside a script run by 'powershell -Command' does not reach the process exit code: end the process itself",
    "  if ($decision -eq 'deny') { [Console]::Error.WriteLine($reason); [Console]::Error.Flush(); [Environment]::Exit(2) }",
    "  exit 0",
    "}",
    "function Canon([string]$x) { ([IO.Path]::GetFullPath($x) -replace '/', '\\').TrimEnd('\\').ToLowerInvariant() }",
    "",
    "try {",
    "  $tool = [string]$p.tool_name",
    "  if (@('Write', 'Edit', 'MultiEdit', 'NotebookEdit') -notcontains $tool) { exit 0 }",
    "  $ti = $p.tool_input",
    "  $file = [string]$ti.file_path",
    "  if (-not $file) { $file = [string]$ti.notebook_path }",
    "  if (-not $file) { exit 0 }",
    "  $root = [string]$env:CLAUDE_PROJECT_DIR",
    "  if (-not $root) { $root = [string]$p.cwd }",
    "  if (-not $root) { $root = Split-Path (Split-Path $PSScriptRoot -Parent) -Parent }",
    "  $abs = if ([IO.Path]::IsPathRooted($file)) { [IO.Path]::GetFullPath($file) } else { [IO.Path]::GetFullPath((Join-Path $root $file)) }",
    "  $c = Canon $abs",
    "  $rc = Canon $root",
    "",
    "  # Rule_Gate_44: inside the project, the temp folders and the host's own folder (~/.claude) are not 'outside'",
    "  $ok = @($root, $env:TEMP, $env:TMP, [IO.Path]::GetTempPath(), (Join-Path $HOME '.claude')) | Where-Object { $_ } | ForEach-Object { Canon $_ }",
    "  $inside = $false",
    "  foreach ($r in $ok) { if ($c -eq $r -or $c.StartsWith($r + '\\')) { $inside = $true } }",
    "  if (-not $inside) {",
    "    Say 'ask' ('Rule_Gate_44_RepoScope: writing ' + $abs + ' - that is OUTSIDE the open project (' + $root + '). Allow it only if this write was asked for.')",
    "  }",
    "",
    "  # Rule_Gate_21: only a code or config file inside the project, the one git would track",
    "  if (-not $c.StartsWith($rc + '\\')) { exit 0 }",
    "  $rel = $abs.Substring($rc.Length + 1) -replace '\\\\', '/'",
    `  $S = ConvertFrom-Json '${secrets.replace(/'/g, "''")}'`,
    "  $code = '\\.(py|js|jsx|ts|tsx|mjs|cjs|json|ya?ml|toml|ini|cfg|conf|ps1|sh|bat|cmd|sql|xml|config|cs|java|go|php|rb)$'",
    "  $notTracked = '(^|/)\\.env(\\.[^/]*)?$|(^|/)data/secrets/|(^|/)gate\\.json$'",
    "  $test = '(^|/)(test|tests|__tests__)/|\\.test\\.[cm]?[jt]sx?$|_test\\.(py|go)$|(^|/)test_[^/]+\\.py$'",
    "  if ($rel -notmatch $code -or $rel -match $notTracked -or $rel -match $S.skipPath) { exit 0 }",
    "",
    "  # what the call ADDS: its lines not already present in what it removes (a multiset of trimmed lines)",
    "  $nl = [string][char]10",
    "  $added = ''; $removed = ''",
    "  if ($tool -eq 'Write') {",
    "    $added = [string]$ti.content",
    "    if (Test-Path -LiteralPath $abs) { try { $removed = [IO.File]::ReadAllText($abs) } catch { $removed = '' } }",
    "  } elseif ($tool -eq 'Edit') {",
    "    $added = [string]$ti.new_string; $removed = [string]$ti.old_string",
    "  } elseif ($tool -eq 'MultiEdit') {",
    "    foreach ($e in @($ti.edits)) { $added += $nl + [string]$e.new_string; $removed += $nl + [string]$e.old_string }",
    "  } else {",
    "    $added = [string]$ti.new_source",
    "  }",
    "  $seen = New-Object 'System.Collections.Generic.Dictionary[string,int]'",
    "  foreach ($l in ($removed -split '\\r?\\n')) { $k = $l.Trim(); if ($k) { if ($seen.ContainsKey($k)) { $seen[$k]++ } else { $seen[$k] = 1 } } }",
    "  $newLines = @()",
    "  foreach ($l in ($added -split '\\r?\\n')) {",
    "    $k = $l.Trim()",
    "    if (-not $k) { continue }",
    "    if ($seen.ContainsKey($k) -and $seen[$k] -gt 0) { $seen[$k]-- } else { $newLines += $l }",
    "  }",
    "",
    "  $envRe = New-Object regex($S.env, 'IgnoreCase')",
    "  $ph = New-Object regex($S.placeholder, 'IgnoreCase')",
    "  $nm = New-Object regex($S.name)",
    "  $hits = @()",
    "  foreach ($l in $newLines) {",
    "    if ($envRe.IsMatch($l)) { continue }",
    "    foreach ($pt in $S.patterns) {",
    "      $opt = if ([string]$pt.flags -match 'i') { 'IgnoreCase' } else { 'None' }",
    "      $m = [regex]::Match($l, $pt.re, $opt)",
    "      if (-not $m.Success) { continue }",
    "      $val = if ($m.Groups.Count -gt 1) { $m.Groups[$m.Groups.Count - 1].Value } else { '' }",
    "      if ($val -and ($ph.IsMatch($val) -or $nm.IsMatch($val))) { continue }",
    "      $shown = if ($val) { $l.Replace($val, '***') } else { [regex]::Replace($l, '[A-Za-z0-9+/=]{12,}', '***') }",
    "      $hits += ([string]$pt.kind + ': ' + $shown.Trim())",
    "      break",
    "    }",
    "  }",
    "  if ($hits.Count -eq 0) { exit 0 }",
    "  $list = (@($hits) | Select-Object -First 4) -join ' | '",
    "  if ($rel -match $test) {",
    "    Say 'ask' ('Rule_Gate_21_WhatEntersGit: a credential-shaped value in the test file ' + $rel + ': ' + $list + '. A fake value is fine here; a real one goes to .env or data/secrets/ and the test reads the environment variable.')",
    "  }",
    "  Say 'deny' ('Rule_Gate_21_WhatEntersGit: a secret value written into ' + $rel + ', a file git tracks: ' + $list + '. A login to a system goes to the machine vault; a secret of this repo''s own product goes to data/secrets/ or .env. The file names where the value is read from (an environment variable or the vault entry), never the value.')",
    "} catch { exit 0 }",
    "",
    // LF: the set's .gitattributes stores *.ps1 as LF, so a fresh checkout must equal what the assembly writes
  ].join("\n");
}

/** The native permission lines the set's rules declare (`gate.json › native: { ask: [...], deny: [...] }`). */
export function nativeLines(parts: Part[]): { ask: string[]; deny: string[] } {
  const out = { ask: [] as string[], deny: [] as string[] };
  for (const p of parts.filter((x) => x.shelf === SHELF.rules)) {
    const f = join(p.dir, "gate.json");
    if (!existsSync(f)) continue;
    let n: { ask?: unknown; deny?: unknown } | undefined;
    try {
      n = (JSON.parse(readFileSync(f, "utf8")) as { native?: { ask?: unknown; deny?: unknown } }).native;
    } catch {
      continue;
    }
    for (const k of ["ask", "deny"] as const) {
      const v = n?.[k];
      if (Array.isArray(v)) for (const l of v) if (typeof l === "string" && !out[k].includes(l)) out[k].push(l);
    }
  }
  return out;
}

interface Settings {
  permissions?: { ask?: string[]; deny?: string[]; [k: string]: unknown };
  hooks?: { PreToolUse?: { matcher?: string; hooks?: { type?: string; command?: string }[] }[]; [k: string]: unknown };
  [k: string]: unknown;
}

/**
 * What the Basic host files would be after an assembly: the guard script, and settings.json with the set's permission
 * lines and the hook added. The permission lines are the repo's (plan/28 §0j): one the repo removed after an assembly
 * recorded it is not added back, its other lines and keys are kept as they are.
 */
export function basicHostFiles(root: string, parts: Part[]): { guard: string; settings: string; recorded: string[] } {
  const want = nativeLines(parts);
  const p = join(root, BASIC_SETTINGS_REL);
  let s: Settings = {};
  if (existsSync(p)) {
    try {
      s = JSON.parse(readFileSync(p, "utf8")) as Settings;
    } catch {
      s = {};
    }
  }
  let marker: Record<string, unknown>;
  try {
    marker = JSON.parse(readFileSync(join(root, "docs", ".harness.json"), "utf8")) as Record<string, unknown>;
  } catch {
    marker = {};
  }
  const before = new Set(Array.isArray(marker[MARKER_KEY]) ? (marker[MARKER_KEY] as unknown[]).map(String) : []);
  const recorded = new Set(before);
  const perms = { ...(s.permissions ?? {}) };
  for (const k of ["ask", "deny"] as const) {
    const list = Array.isArray(perms[k]) ? [...(perms[k] as string[])] : [];
    for (const l of want[k]) {
      const tag = `${k}:${l}`;
      if (!list.includes(l) && !before.has(tag)) list.push(l);
      recorded.add(tag);
    }
    if (list.length) perms[k] = list;
  }
  const hooks = { ...(s.hooks ?? {}) };
  const pre = Array.isArray(hooks.PreToolUse) ? [...hooks.PreToolUse] : [];
  if (!pre.some((e) => (e.hooks ?? []).some((h) => h.command === BASIC_GUARD_COMMAND))) {
    pre.push({ matcher: BASIC_MATCHER, hooks: [{ type: "command", command: BASIC_GUARD_COMMAND }] });
  }
  hooks.PreToolUse = pre;
  const next: Settings = { ...s, permissions: perms, hooks };
  return { guard: basicGuardSource(), settings: JSON.stringify(next, null, 2) + "\n", recorded: [...recorded].sort() };
}

/** True when the Basic host files on disk are what an assembly would write. */
export function basicHostCurrent(root: string, parts: Part[]): boolean {
  const f = basicHostFiles(root, parts);
  const read = (rel: string): string | null => (existsSync(join(root, rel)) ? readFileSync(join(root, rel), "utf8") : null);
  return read(BASIC_GUARD_REL) === f.guard && read(BASIC_SETTINGS_REL) === f.settings;
}

/** Write the Basic host files; returns the repo-relative paths written. */
export function writeBasicHost(root: string, parts: Part[], apply: boolean): string[] {
  const f = basicHostFiles(root, parts);
  const written: string[] = [];
  for (const [rel, text] of [[BASIC_GUARD_REL, f.guard], [BASIC_SETTINGS_REL, f.settings]] as const) {
    const p = join(root, rel);
    if (existsSync(p) && readFileSync(p, "utf8") === text) continue;
    if (apply) {
      mkdirSync(dirname(p), { recursive: true });
      writeFileSync(p, text);
    }
    written.push(rel);
  }
  const mp = join(root, "docs", ".harness.json");
  if (apply && existsSync(mp)) {
    try {
      const m = JSON.parse(readFileSync(mp, "utf8")) as Record<string, unknown>;
      const cur = Array.isArray(m[MARKER_KEY]) ? (m[MARKER_KEY] as unknown[]).map(String).sort() : [];
      if (f.recorded.length && JSON.stringify(cur) !== JSON.stringify(f.recorded)) {
        m[MARKER_KEY] = f.recorded;
        writeFileSync(mp, JSON.stringify(m, null, 2) + "\n");
      }
    } catch {
      /* an unreadable marker: the lines are written, only the record of them is not */
    }
  }
  return written;
}
