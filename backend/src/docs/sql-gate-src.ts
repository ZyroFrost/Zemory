// 02-25 "SQL — 1 CÁCH" — layer-1 hook (user 2026-10-14, plan/27 §2g): a NEW SQL string written straight into code is
// blocked at write time. If the same query already has a name in a `store/queries.*` file the message names it; if not,
// the agent is told to add ONE named entry there. The ratchet test (`sql-one-way.test.mjs` in zemory) covers what this
// hook cannot see (SQL assembled through variables).
//
// Comparison = case- and whitespace-insensitive (that is what made `count(*)` and `COUNT(*)` one query). Only SQL that the
// edit ADDS is judged: moving or re-indenting an existing call is not a new query. Inactive until the repo has at least one
// store file (policy.sql is written only then), so a repo that has not adopted the rule is never blocked by surprise.
//
// The block message carries the rule text itself, read from the repo's own 02_RULES at run time (plan/27 §4) — the agent
// does not have to open the rules to learn what it broke. Every failure lets the action through (a broken hook must not
// block blindly).
//
// Generated into `<hooks>/02-25_sql-one-way.cjs` by `zemory hook guard`; guard.cjs calls it. Written with String.raw so
// backslashes are literal — DO NOT use backticks or dollar-brace inside the source below.
export const SQL_GATE_FILE = "02-25_sql-one-way.cjs";

export const SQL_GATE_SOURCE = String.raw`// 02-25 SQL one way - generated by zemory hook guard. The settings live in policy.json (sql).
"use strict";
const fs = require("node:fs");
const path = require("node:path");

const BT = String.fromCharCode(96);
const norm = (s) => String(s).replace(/\s+/g, " ").trim().toLowerCase();
const LITERAL = () => new RegExp("\\.prepare\\(\\s*([\"'" + BT + "])([\\s\\S]*?)\\1\\s*,?\\s*\\)", "g");
const NAMED = () => new RegExp("^\\s*(\\w+):\\s*([\"'" + BT + "])([\\s\\S]*?)\\2,\\s*$", "gm");

function literals(text) {
  const out = [];
  for (const m of String(text || "").matchAll(LITERAL())) out.push(m[2]);
  return out;
}

function namedQueries(root, stores) {
  const out = new Map();
  for (const rel of stores || []) {
    let txt = "";
    try { txt = fs.readFileSync(path.join(root, rel), "utf8"); } catch { continue; }
    for (const m of txt.matchAll(NAMED())) if (!out.has(norm(m[3]))) out.set(norm(m[3]), { name: m[1], store: rel });
  }
  return out;
}

// The rule's own text: the line carrying its number plus its continuation lines, capped.
function ruleText(root, file, id) {
  try {
    const lines = fs.readFileSync(path.join(root, file), "utf8").split(/\r?\n/);
    const at = lines.findIndex((l) => l.includes(BT + id + BT) || l.startsWith(id + " "));
    if (at < 0) return "";
    const out = [lines[at]];
    for (let i = at + 1; i < lines.length && out.length < 12; i++) {
      const l = lines[i];
      if (!l.trim() || /^(- |#|\x60\x60\x60|\d{2}-\d+ )/.test(l)) break;
      out.push(l);
    }
    return out.map((l) => (l.length > 400 ? l.slice(0, 400) + "…" : l)).join("\n");
  } catch {
    return "";
  }
}

function check(payload, root, policy) {
  try {
    const sql = policy && policy.sql;
    if (!sql || !Array.isArray(sql.stores) || sql.stores.length === 0) return null;
    const tool = payload.tool_name || "";
    if (tool !== "Write" && tool !== "Edit" && tool !== "MultiEdit") return null;
    const ti = payload.tool_input || {};
    const abs = ti.file_path || "";
    if (!abs) return null;
    const rel = path.relative(root, path.resolve(root, abs)).replace(/\\/g, "/");
    if (rel.startsWith("..") || path.isAbsolute(rel)) return null;
    if (!(sql.code_ext || []).some((e) => rel.toLowerCase().endsWith(e))) return null;
    if ((sql.exclude || []).some((p) => rel.startsWith(p))) return null;
    if (/(^|\/)store\/queries\.[a-z]+$/i.test(rel)) return null;

    let added = "", removed = "";
    if (tool === "Write") {
      added = ti.content || "";
      try { removed = fs.existsSync(abs) ? fs.readFileSync(abs, "utf8") : ""; } catch { removed = ""; }
    } else if (tool === "Edit") {
      added = ti.new_string || ""; removed = ti.old_string || "";
    } else {
      for (const e of ti.edits || []) { added += "\n" + (e.new_string || ""); removed += "\n" + (e.old_string || ""); }
    }
    const before = new Map();
    for (const s of literals(removed)) before.set(norm(s), (before.get(norm(s)) || 0) + 1);
    const fresh = [];
    for (const s of literals(added)) {
      const k = norm(s);
      const n = before.get(k) || 0;
      if (n > 0) before.set(k, n - 1); else fresh.push(s);
    }
    if (fresh.length === 0) return null;

    const named = namedQueries(root, sql.stores);
    const lines = fresh.map((s) => {
      const short = norm(s).slice(0, 90);
      if (s.includes("$" + "{")) return "  - built at run time: " + short + "\n    -> assemble it inside a store file, not at the call site";
      const hit = named.get(norm(s));
      if (hit) return "  - " + short + "\n    -> ALREADY NAMED: use Q." + hit.name + " (" + hit.store + ")";
      return "  - " + short + "\n    -> not named yet: add ONE named entry to " + sql.stores[0] + " and call it by name";
    });
    const text = ruleText(root, sql.rules_file || "", sql.rule || "02-25");
    return "BLOCKED (guard layer 1): rule " + (sql.rule || "02-25") + " - new SQL written inline in " + rel + ":\n" +
      lines.join("\n") + (text ? "\n\nThe rule (" + sql.rules_file + "):\n" + text : "");
  } catch {
    return null;
  }
}

module.exports = { check };
`;
